class I18nManager {
    constructor() {
        this.idiomaAtual = localStorage.getItem('recife_mca_idioma') || 'pt';
        if (!traducoes[this.idiomaAtual]) {
            this.idiomaAtual = 'pt';
        }
    }

    getIdioma() {
        return this.idiomaAtual;
    }

    setIdioma(lang) {
        if (!traducoes[lang]) return;
        this.idiomaAtual = lang;
        localStorage.setItem('recife_mca_idioma', lang);
        this.aplicarTraducoes();

        // Notifica o Store se disponível
        if (typeof store !== 'undefined' && store.setIdioma) {
            store.setIdioma(lang);
        }
    }

    t(chave) {
        const pacote = traducoes[this.idiomaAtual] || traducoes.pt;
        return pacote[chave] || traducoes.pt[chave] || chave;
    }

    aplicarTraducoes() {
        // Traduz elementos com atributo data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const chave = el.getAttribute('data-i18n');
            const texto = this.t(chave);
            if (texto) el.textContent = texto;
        });

        // Traduz placeholders de inputs com data-i18n-placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const chave = el.getAttribute('data-i18n-placeholder');
            const texto = this.t(chave);
            if (texto) el.setAttribute('placeholder', texto);
        });

        // Atualiza botões de idioma na barra
        ['pt', 'en', 'es'].forEach(l => {
            const btn = document.getElementById(`btn-lang-${l}`);
            if (!btn) return;
            if (l === this.idiomaAtual) {
                btn.className = "px-2 py-0.5 text-[10px] font-bold rounded bg-white text-slate-800 shadow-xs transition";
            } else {
                btn.className = "px-2 py-0.5 text-[10px] font-medium text-slate-500 hover:text-slate-800 transition";
            }
        });
    }
}

